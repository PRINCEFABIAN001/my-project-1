function showmenu() {
    var menu =
    document.getElementById("MENULIST"
    );

    IF(MENU.style.DISPLAY  ===
    "NONE") 
     {
              menu.style.display =
              "block";
              alert("menu is now open");
    } 
      { 
        menu.style.display = "none";
      alert("menu is now hidden!");
    
    }
}